# Metric 2 — Narrative Transition Entropy
# Entropy of the distribution of sentiment changes between segments.
# Low entropy = predictable/formulaic transitions.

def transition_entropy(arc: np.ndarray) -> float:
    """
    Compute entropy of discretized sentiment transitions.
    Transitions: UP (+), FLAT (=), DOWN (-)
    """
    diffs = np.diff(arc)
    bins = np.array([-1 if d < -0.05 else (1 if d > 0.05 else 0) for d in diffs])
    counts = np.array([(bins == v).sum() for v in [-1, 0, 1]], dtype=float)
    counts = counts[counts > 0]
    probs = counts / counts.sum()
    return float(scipy_entropy(probs, base=2))


