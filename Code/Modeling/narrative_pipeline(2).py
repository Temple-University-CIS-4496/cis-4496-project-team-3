def get_sentiment_arc(text: str, n_segments: int = N_SEGMENTS) -> np.ndarray:
    """
    Split script into n equal segments, compute mean VADER compound
    sentiment score per segment. Returns array of shape (n_segments,).
    """
    sentences = nltk.sent_tokenize(text)
    if len(sentences) < n_segments:
        return None

    seg_size = len(sentences) // n_segments
    arc = []
    for i in range(n_segments):
        seg = sentences[i * seg_size: (i + 1) * seg_size]
        scores = [sia.polarity_scores(s)["compound"] for s in seg]
        arc.append(np.mean(scores))

    return np.array(arc)


